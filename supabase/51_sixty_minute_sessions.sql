-- ============================================================
-- ٥١) الجلسة الخاصة ستّون دقيقة — للكوتشات الموجودات أيضاً
--
-- الهجرة ٤٣ غيّرت الافتراضيّ إلى ٦٠، والافتراضيّ لا يمسّ صفّاً
-- قائماً: كوتشٌ أُضيف قبلها ما زال على ثلاثين، فتُولَّد مواعيده
-- نصف ساعة بينما تعلن الصفحة ساعة. العنوان يَعِد بما لا يُحجَز.
--
-- يُرفَع كل كوتشٍ إلى ستّين. والحجوزات القائمة لا تُمَسّ: مدّتها
-- مخزَّنة في class_slots ساعةَ الحجز، وتمديدُها بأثرٍ رجعيّ قد
-- يتداخل مع موعدٍ بعده ويصطدم بقيد عدم التداخل — ومن حجزت نصف
-- ساعة حجزت نصف ساعة. الجديد وحده ستّون.
--
-- الهجرة idempotent.
-- ============================================================

update public.coaches set slot_min = 60 where slot_min is distinct from 60;

-- وتوفّر الكوتشات في نافذة الحجز المعتمدة: الاثنين إلى الخميس
-- ٦ إلى ١١ مساءً. تُترك كما هي إن كانت مضبوطة أصلاً.
update public.booking_policy
   set open_weekdays = '{1,2,3,4}'
 where id and open_weekdays is distinct from '{1,2,3,4}'::smallint[];

notify pgrst, 'reload schema';
